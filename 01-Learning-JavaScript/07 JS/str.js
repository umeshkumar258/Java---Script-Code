console.log("String Accessing 🚀");

const str = "Umesh";

// Accessing characters using index
console.log("First character:", str[0]);
console.log("Second character:", str[1]);
console.log("Third character:", str[2]);
console.log("Fourth character:", str[3]);
console.log("Fifth character:", str[4]);

// Accessing the last character dynamically
console.log("Last character:", str[str.length - 1]);

// Checking the length
console.log("Length:", str.length);

// Using charAt()
console.log("Character at index 2:", str.charAt(2));

// Invalid index
console.log("Invalid index:", str[10]);
